"""Create (once) or reuse the patient-grouped train / validation / test split.

First run:  reads label + patient ID of every .mat file, checks that each
            patient has one tumor type, splits by patient group, and saves
            splits/split_v1.csv + splits/split_v1.json.
Later runs: finds the saved split, checks it is intact and still matches the
            dataset, and reuses it unchanged. To make a new split you must
            delete those two files yourself (nothing is overwritten silently).

Every run rewrites reports/split_report.md. Nothing is trained here.

Run:  python src\\make_split.py
"""

from config import (EXPECTED_FILE_NUMBERS, LABEL_NAMES, MAT_DIR, REPORTS_DIR,
                    SPLIT_CSV, SPLIT_FRACTIONS, SPLIT_JSON, SPLIT_SEED)
from mat_loader import load_metadata
from splitting import (SPLIT_NAMES, ImageRecord, SplitError, assign_splits,
                       build_groups, check_label_consistency, load_split,
                       save_split, summarize_split)

# Report a tumor type's share of a split as off-target beyond this (0.05 = 5 points).
BALANCE_WARN = 0.05


def read_records(mat_dir=MAT_DIR, numbers=EXPECTED_FILE_NUMBERS):
    """Return one ImageRecord per expected .mat file (1.mat ... 3064.mat by default).

    Every expected image is required: a missing, unreadable or invalid file stops
    the script instead of being skipped, so a split can never silently leave images out.
    """
    if not mat_dir.exists():
        raise SystemExit(f"No extracted data at {mat_dir}. Run: python src\\prepare_data.py")
    paths = [mat_dir / f"{n}.mat" for n in numbers]
    missing = [p.name for p in paths if not p.exists()]
    if missing:
        raise SystemExit(f"{len(missing)} .mat files missing (e.g. {missing[:5]}). Run: python src\\prepare_data.py")

    records = []
    for path in paths:
        try:
            label, pid = load_metadata(path)
        except Exception as e:
            raise SystemExit(f"Could not read {path.name}: {type(e).__name__}: {e}")
        if label not in LABEL_NAMES or not pid:
            raise SystemExit(f"{path.name} has label {label!r} and patient ID {pid!r}; expected a valid pair.")
        records.append(ImageRecord(file=path.name, pid=pid, label=label))
    return records


def ensure_split(records, csv_path, json_path, seed, fractions):
    """Return (assignment, "created" | "reused"). Reuses a saved split if there is one."""
    if csv_path.exists() and json_path.exists():
        assignment, _ = load_split(csv_path, json_path, records)
        return assignment, "reused"
    if csv_path.exists() or json_path.exists():
        raise SplitError(f"Only one of {csv_path.name} / {json_path.name} exists. Restore both from Git, "
                         "or delete both to make a new split.")
    save_split(csv_path, json_path, records, assign_splits(records, fractions, seed), seed, fractions)
    assignment, _ = load_split(csv_path, json_path, records)  # read back what was written, as a check
    return assignment, "created"


def pct(part, whole):
    return f"{100 * part / whole:.1f}%" if whole else "n/a"


def write_report(records, assignment, meta, status, path):
    summary = summarize_split(records, assignment)
    labels = sorted(LABEL_NAMES)
    n_groups = len(build_groups(records))
    images = {s: sum(summary[s][lab]["images"] for lab in labels) for s in SPLIT_NAMES}
    groups = {s: sum(summary[s][lab]["groups"] for lab in labels) for s in SPLIT_NAMES}
    total_by_label = {lab: sum(summary[s][lab]["images"] for s in SPLIT_NAMES) for lab in labels}

    L = ["# Patient-grouped split report\n",
         f"Generated by `src/make_split.py`. This run **{status}** the split in "
         f"`splits/{meta['split_file']}` (created {meta['created_utc']}, seed {meta['seed']}, "
         f"algorithm version {meta['algorithm_version']}). Nothing is trained here.\n",
         "## Checks (all must pass, or the script stops)",
         f"- Every image assigned exactly once: {len(assignment)} of {len(records)} images",
         f"- Each patient ID and each patient group has one tumor type: yes",
         f"- Patient groups split across more than one set: 0 of {n_groups} "
         "(look-alike IDs such as `MR040240` / `MR040240B` count as one group)",
         "- Split file matches its saved fingerprints and the current dataset: yes\n",
         "## Split sizes",
         "| Split | Target | Images | Share of images | Patient groups |",
         "|---|---|---|---|---|"]
    for s in SPLIT_NAMES:
        L.append(f"| {s} | {meta['fractions'][s]:.0%} | {images[s]} | {pct(images[s], len(records))} | {groups[s]} |")
    L.append(f"| **total** | | **{len(records)}** | | **{n_groups}** |\n")

    L.append("## Class balance: images (patient groups) per tumor type")
    L.append("Each tumor type is split on its own, so its share in every split should be near the target.\n")
    L.append("| Tumor type | " + " | ".join(SPLIT_NAMES) + " | total |")
    L.append("|---|" + "---|" * (len(SPLIT_NAMES) + 1))
    warnings = []
    for lab in labels:
        cells = []
        for s in SPLIT_NAMES:
            c = summary[s][lab]
            share = c["images"] / total_by_label[lab]
            flag = ""
            if abs(share - meta["fractions"][s]) > BALANCE_WARN:
                flag = " ⚠️"
                warnings.append(f"{LABEL_NAMES[lab]} in {s}: {share:.1%} vs target {meta['fractions'][s]:.0%}")
            cells.append(f"{c['images']} ({c['groups']}) = {share:.1%}{flag}")
        L.append(f"| {LABEL_NAMES[lab]} | " + " | ".join(cells) + f" | {total_by_label[lab]} |")
    L.append("")
    L.append("Tumor-type mix inside each split (share of that split's images):\n")
    L.append("| Split | " + " | ".join(LABEL_NAMES[lab] for lab in labels) + " |")
    L.append("|---|" + "---|" * len(labels))
    L.append("| whole dataset | " + " | ".join(pct(total_by_label[lab], len(records)) for lab in labels) + " |")
    for s in SPLIT_NAMES:
        L.append(f"| {s} | " + " | ".join(pct(summary[s][lab]["images"], images[s]) for lab in labels) + " |")
    L.append("")
    if warnings:
        L.append(f"Shares more than {BALANCE_WARN:.0%} points off target (expected sometimes, because whole "
                 "patients move together and some have many images): " + "; ".join(warnings) + "\n")
    else:
        L.append(f"Every tumor type's share of every split is within {BALANCE_WARN:.0%} points of its target.\n")

    L.append("## Notes")
    L.append("- Image shares can't be exactly 70/15/15: patient groups have 1 to 97 images and are never divided.")
    fewest = min(((summary[s][lab]["groups"], LABEL_NAMES[lab], s) for s in ("val", "test") for lab in labels))
    L.append(f"- Validation and test hold only {groups['val']} and {groups['test']} patient groups. The smallest "
             f"cell is {fewest[1]} in {fewest[2]}, with just {fewest[0]} patient groups, because those patients "
             "have many images each. Later scores per tumor type will be noisy; that is a limit of the "
             "dataset's size, not something a different seed can fix.")
    L.append("- Grouping look-alike IDs is a cautious assumption (the README doesn't explain the suffixes).")
    path.write_text("\n".join(L) + "\n", encoding="utf-8")
    return warnings


def main():
    print(f"Reading label and patient ID from {MAT_DIR}")
    records = read_records()
    print(f"  {len(records)} images, {len({r.pid for r in records})} patient IDs, "
          f"{len(build_groups(records))} patient groups")
    try:
        check_label_consistency(records)
        print("  label consistency: OK (one tumor type per patient ID and per patient group)")
        assignment, status = ensure_split(records, SPLIT_CSV, SPLIT_JSON, SPLIT_SEED, SPLIT_FRACTIONS)
        _, meta = load_split(SPLIT_CSV, SPLIT_JSON, records)
    except SplitError as e:
        raise SystemExit(f"STOPPED: {e}")

    print(f"Split {status}: {SPLIT_CSV}")
    REPORTS_DIR.mkdir(exist_ok=True)
    report = REPORTS_DIR / "split_report.md"
    warnings = write_report(records, assignment, meta, status, report)
    summary = summarize_split(records, assignment)
    for s in SPLIT_NAMES:
        counts = ", ".join(f"{LABEL_NAMES[lab]} {summary[s][lab]['images']}" for lab in sorted(LABEL_NAMES))
        print(f"  {s:5}: {sum(c['images'] for c in summary[s].values()):4} images | {counts}")
    for w in warnings:
        print(f"  note: {w}")
    print(f"Report written to {report}")


if __name__ == "__main__":
    main()
